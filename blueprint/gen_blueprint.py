#!/usr/bin/env python3
"""gen_blueprint.py -- build the blueprint of the APN2 paper from nodes.json.
usage: python3 gen_blueprint.py PAPER_AUX LEAN_DIR OUT_DIR
Checks (exit 1 on failure): every paper label exists in the aux file; every Lean declaration named in nodes.json is
audited in LEAN_DIR/Audit.lean (#print axioms) and defined in exactly one module of LEAN_DIR/Apn2R03; every
dependency is a node. Writes OUT_DIR/blueprint.tex, dep_graph.dot, lean_imports.dot and check.txt."""
import json, re, sys, glob, os
aux, lean, out = sys.argv[1:4]
here = os.path.dirname(os.path.abspath(__file__))
N = json.load(open(os.path.join(here, 'nodes.json'), encoding='utf-8'))
labels = {}
for m in re.finditer(r'\\newlabel\{([^}]*)\}\{\{([^}]*)\}\{([^}]*)\}', open(aux, encoding='utf-8').read()):
    labels[m.group(1)] = (m.group(2), m.group(3))
audit = re.findall(r'#print axioms (\S+)', open(os.path.join(lean, 'Audit.lean'), encoding='utf-8').read())
byshort = {}
for a in audit: byshort.setdefault(a.split('.')[-1], []).append(a)
mods = {}
for f in sorted(glob.glob(os.path.join(lean, 'Apn2R03', '*.lean'))):
    mods[os.path.basename(f)[:-5]] = open(f, encoding='utf-8').read()
errs = []
ids = {n['id'] for n in N['nodes']}
rows = []
for n in N['nodes']:
    if n['label'] not in labels: errs.append('label missing: ' + n['label'])
    for dpd in n['deps']:
        if dpd not in ids: errs.append('dependency missing: %s -> %s' % (n['id'], dpd))
    full = []
    for s in n['decls']:
        a = byshort.get(s, [])
        if len(a) != 1: errs.append('not audited exactly once: ' + s); continue
        pat = re.compile(r'^\s*(?:private\s+)?(?:noncomputable\s+)?(?:theorem|lemma|def|abbrev|instance)\s+' + re.escape(s) + r'(?![\w\'])', re.M)
        where = [m for m, t in mods.items() if pat.search(t)]
        if len(where) != 1: errs.append('defined in %d modules: %s' % (len(where), s)); continue
        full.append((a[0], where[0]))
    rows.append((n, full))
os.makedirs(out, exist_ok=True)
nd = sum(len(f) for _, f in rows)
chk = ['nodes %d' % len(rows), 'declarations %d (all audited in Audit.lean, each defined in one module)' % nd,
       'audited declarations in Audit.lean %d' % len(audit)] + errs
open(os.path.join(out, 'check.txt'), 'w').write('\n'.join(chk) + '\n' + ('BLUEPRINT_CHECK=PASS\n' if not errs else 'BLUEPRINT_CHECK=FAIL\n'))
if errs: print('\n'.join(errs)); sys.exit(1)
def tx(s): return s.replace('_', r'\_').replace('&', r'\&').replace('#', r'\#').replace('%', r'\%')
def math(s):
    s = tx(s)
    s = s.replace('P\\_{m,r}', '$P_{m,r}$').replace('P\\_{7,5}', '$P_{7,5}$').replace('P\\_{7,3}', '$P_{7,3}$').replace('P\\_{9,5}', '$P_{9,5}$').replace('P\\_{9,7}', '$P_{9,7}$')
    s = s.replace('mu=0', '$\\mu=0$').replace('N >= 2', '$N\\ge2$').replace('m <= 13', '$m\\le13$').replace('k=3', '$k=3$')
    s = s.replace('t^17+t^3+1', '$t^{17}+t^3+1$').replace('F\\_(2^17)', '$\\mathbb{F}_{2^{17}}$').replace('GR(4,2)', '$\\mathrm{GR}(4,2)$').replace('B=3', '$B=3$').replace('m=5', '$m=5$').replace('m=7', '$m=7$').replace('Z empty', '$Z=\\emptyset$').replace('p\\_d', '$p_d$').replace('p\\_c', '$p_c$')
    return s
ST = {'formal': 'formalized', 'formal-core': 'core formalized; parts on paper', 'formal-special': 'formalized for the family $P_{m,r}$; general case on paper'}
L = [r'''\documentclass[11pt]{article}
\usepackage[T1]{fontenc}\usepackage[utf8]{inputenc}\usepackage{lmodern}\usepackage{amsmath,amssymb}
\usepackage[margin=1in]{geometry}\usepackage{longtable,booktabs}\usepackage{graphicx}\usepackage[hidelinks]{hyperref}
\title{Blueprint: Coefficient choice in Galois-ring lifts of APN permutations}
\author{Hiroki Fukui}
\date{Version 2.0.0, 27 October 2026}
\begin{document}\maketitle
\section*{Purpose}
This blueprint maps every result of the paper \emph{Coefficient choice in Galois-ring lifts of APN permutations: sharp
unit-direction spectra and one-term optimal lifts} to the Lean~4 declarations that formalize it, states what remains
on paper, and names the finite computations that cross-check it. Numbers refer to the paper (\texttt{paper/manuscript.pdf}).
The Lean development is in \texttt{supplement/lean} (Lean 4.31.0-rc1, Mathlib \texttt{d568c8c}): 55 modules, the root
\texttt{Apn2R03.lean} and \texttt{Audit.lean}. \texttt{Audit.lean} prints the axioms of %d declarations; in the author's
clean build every one depends only on \texttt{propext}, \texttt{Classical.choice} and \texttt{Quot.sound}, and no
declaration uses \texttt{sorry}. This blueprint was generated by \texttt{blueprint/gen\_blueprint.py}, which checks that
every declaration named below is audited in \texttt{Audit.lean} and defined in exactly one module.

\paragraph{Settings.} Most results are proved for an abstract finite ring $R$ with a surjection onto a finite field $K$
whose kernel is $2R$, with $2^k=0$ and $2$-torsion $2^{k-1}R$; the declarations \texttt{grs}, \texttt{grs\_card} and
\texttt{exists\_GR\_poly} show that $\mathrm{GR}(2^k,m)$ satisfies these axioms, and the declarations ending in
\texttt{\_GR} state results on the concrete ring. Difference counts are cardinalities of actual finite solution sets.

\paragraph{Status.} %d nodes; ``formalized'' means that every mathematical claim of the item is a Lean theorem;
otherwise the paper-only parts are listed.
''' % (len(audit), len(rows))]
L.append(r'\begin{longtable}{p{0.13\textwidth}p{0.47\textwidth}p{0.32\textwidth}}\toprule Paper & Item & Status\\\midrule\endhead')
for n, full in rows:
    num, page = labels[n['label']]
    kind = n['label'].split(':')[0]
    pre = {'thm': 'Theorem', 'lem': 'Lemma', 'prop': 'Proposition', 'cor': 'Corollary', 'sec': 'Section', 'ex': 'Example'}[kind]
    L.append('%s %s & %s & %s\\\\' % (pre, num, math(n['title']), ST[n['status']]))
L.append(r'\bottomrule\end{longtable}')
for n, full in rows:
    num, page = labels[n['label']]
    pre = {'thm': 'Theorem', 'lem': 'Lemma', 'prop': 'Proposition', 'cor': 'Corollary', 'sec': 'Section', 'ex': 'Example'}[n['label'].split(':')[0]]
    L.append(r'\subsection*{%s %s (p.~%s): %s}' % (pre, num, page, math(n['title'])))
    L.append(r'\textbf{Status:} %s.\par' % ST[n['status']])
    L.append(r'\textbf{Lean:}\begin{itemize}\setlength\itemsep{0pt}')
    for a, m in full: L.append(r'\item \texttt{%s} \hfill (\texttt{Apn2R03/%s.lean})' % (tx(a), m))
    L.append(r'\end{itemize}')
    if n['paper']: L.append(r'\textbf{On paper only:} %s.\par' % math(n['paper']))
    if n['checks']: L.append(r'\textbf{Computational cross-check:} %s.\par' % math(n['checks']))
    if n['deps']:
        L.append(r'\textbf{Uses:} %s.\par' % ', '.join('%s %s' % ({'thm':'Theorem','lem':'Lemma','prop':'Proposition','cor':'Corollary','sec':'Section'}[[x for x in N['nodes'] if x['id']==d0][0]['label'].split(':')[0]], labels[[x for x in N['nodes'] if x['id']==d0][0]['label']][0]) for d0 in n['deps']))
L.append(r'''\section*{Not formalized}
The operation counts in the termwise evaluation model; the coefficient formulas and the existence and counting arguments
for the representative families (Theorems 10.1 and 10.2); Proposition 8.6 and the classification of the remaining
intermediate-layer configurations; the passage from two to $N\ge2$ rounds in Propositions 9.5 and 9.6; Proposition 10.3
beyond the family $P_{m,r}$; the probability comparison in Proposition 9.8. The finite computations are replayed by
\texttt{supplement/replay\_core.sh} and \texttt{supplement/replay\_full.sh}.
\section*{Dependency graph of the items}
\begin{center}\includegraphics[width=\textwidth,height=0.8\textheight,keepaspectratio]{dep_graph.pdf}\end{center}
\section*{Import graph of the Lean modules}
\begin{center}\includegraphics[width=\textwidth,height=0.85\textheight,keepaspectratio]{lean_imports.pdf}\end{center}
\end{document}''')
open(os.path.join(out, 'blueprint.tex'), 'w', encoding='utf-8').write('\n'.join(L))
g = ['digraph items {', ' rankdir=BT; node [shape=box, fontsize=10];']
for n, _ in rows:
    num = labels[n['label']][0]
    col = {'formal': 'palegreen', 'formal-core': 'khaki', 'formal-special': 'lightblue'}[n['status']]
    g.append(' "%s" [label="%s %s", style=filled, fillcolor=%s];' % (n['id'], n['label'].split(':')[0], num, col))
    for d0 in n['deps']: g.append(' "%s" -> "%s";' % (n['id'], d0))
g.append('}')
open(os.path.join(out, 'dep_graph.dot'), 'w').write('\n'.join(g))
h = ['digraph imports {', ' rankdir=BT; node [shape=box, fontsize=9];']
for m, t in mods.items():
    for imp in re.findall(r'^import Apn2R03\.(\w+)', t, re.M): h.append(' "%s" -> "%s";' % (m, imp))
h.append('}')
open(os.path.join(out, 'lean_imports.dot'), 'w').write('\n'.join(h))
print('BLUEPRINT_CHECK=PASS nodes %d declarations %d' % (len(rows), nd))
